#!/usr/bin/env python3
"""Run every component's tests in dependency order and show who is blocked by whom.

  tools/status.py              # table to stdout
  tools/status.py --vault      # also write <vault>/STATUS.md (agents: run this before reporting)
  tools/status.py rhythm chop  # only these components (deps still shown)
"""
import datetime, json, os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
cfg = json.load(open(os.path.join(ROOT, "deps.json")))
comps = cfg["components"]


def topo():
    seen, out = set(), []
    def visit(n):
        if n not in seen:
            seen.add(n)
            for d in comps[n]["deps"]:
                visit(d)
            out.append(n)
    for n in comps:
        visit(n)
    return out


def run(name):
    p = subprocess.run(comps[name]["cmd"], shell=True, cwd=ROOT, capture_output=True, text=True, timeout=900)
    out = p.stdout + p.stderr
    m = re.search(r"Ran (\d+) tests?", out)
    if m:  # unittest
        total = int(m.group(1))
        bad = sum(int(x) for x in re.findall(r"(?:failures|errors)=(\d+)", out))
        skipped = sum(int(x) for x in re.findall(r"skipped=(\d+)", out))
        passed = max(0, total - bad - skipped)
        total = max(total, passed + bad + skipped)  # setUpClass errors are not counted by "Ran N"
    else:  # node --test
        g = lambda k: int((re.search(rf"(?:#|ℹ) {k} (\d+)", out) or [0, 0])[1])
        passed, bad, skipped = g("pass"), g("fail"), g("skipped")
        total = passed + bad + skipped
    first_err = next((l.strip() for l in out.splitlines() if re.search(r"NotImplementedError|not implemented|Error:", l)), "")
    return {"ok": p.returncode == 0 and bad == 0, "passed": passed, "total": total, "skipped": skipped, "hint": first_err[:110]}


def main():
    only = [a for a in sys.argv[1:] if not a.startswith("--")]
    res = {}
    for n in topo():
        if only and n not in only:
            continue
        res[n] = run(n)
    rows = []
    for n in topo():
        if n not in res:
            continue
        r = res[n]
        blockers = [d for d in comps[n]["deps"] if d in res and not res[d]["ok"]]
        state = "GREEN" if r["ok"] else ("RED · blocked by " + ", ".join(blockers) if blockers else "RED")
        rows.append((n, comps[n]["owner"], ", ".join(comps[n]["deps"]) or "—", f'{r["passed"]}/{r["total"]}' + (f' (+{r["skipped"]} skip)' if r['skipped'] else ''), state, r["hint"]))
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    md = [f"# ChopPad test status — {ts}", "", "Generated by `tools/status.py --vault`. Do not edit by hand.", "",
          "| component | owner | depends on | pass | state | first failure |", "|---|---|---|---|---|---|"]
    md += [f"| {' | '.join(r[:5])} | `{r[5]}` |" for r in rows]
    md += ["", "```mermaid", "graph LR"]
    md += [f"  {d} --> {n}" for n in comps for d in comps[n]["deps"]]
    md += [f"  style {r[0]} fill:{'#79b58d' if r[4] == 'GREEN' else '#c47070'}" for r in rows] + ["```"]
    w = [max(len(r[i]) for r in rows + [("component", "owner", "depends on", "pass", "state", "")]) for i in range(5)]
    for r in [("component", "owner", "depends on", "pass", "state", "first failure")] + rows:
        print("  ".join(c.ljust(w[i]) for i, c in enumerate(r[:5])), " ", r[5])
    if "--vault" in sys.argv:
        path = os.path.join(os.path.expanduser(cfg["vault"]), "STATUS.md")
        open(path, "w").write("\n".join(md) + "\n")
        print("wrote", path)
    sys.exit(0 if all(r["ok"] for r in res.values()) else 1)


if __name__ == "__main__":
    main()
